// The picture of a channel's name: a dark 128x128 tile with the channel's last
// segment in large letters, and the segment before it in small letters above.
// Node has no image library built in, so this file holds a 5x7 bitmap font,
// draws it scaled, and encodes the PNG with node:zlib.

import { existsSync, mkdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { crc32, deflateSync, inflateSync } from 'node:zlib';

