function glyph(ch) {
  if (ch === ELLIPSIS) return [0x40, 0x00, 0x40, 0x00, 0x40];
  const code = ch.codePointAt(0);
  // A character the font lacks shows as a box.
  return COLUMNS[code - 0x20] ?? [0x7f, 0x41, 0x41, 0x41, 0x7f];
}

// Width in pixels of text drawn at scale: five columns and one gap per letter.
function textWidth(text, scale) {
  const n = [...text].length;
  return n === 0 ? 0 : (n * 6 - 1) * scale;
}

// The longest start of text that fits in width, ending in … when cut.
function fit(text, scale, width) {
  const chars = [...text];
  if (textWidth(text, scale) <= width) return text;
  while (chars.length > 0 && textWidth(chars.join('') + ELLIPSIS, scale) > width) chars.pop();
  return chars.join('') + ELLIPSIS;
}

class Canvas {
  constructor() {
    this.pixels = Buffer.alloc(SIZE * SIZE * 3);
    for (let i = 0; i < SIZE * SIZE; i++) this.pixels.set(BACKGROUND, i * 3);
  }

  fillRect(x, y, w, h, color) {
    for (let j = y; j < y + h; j++) {
      for (let i = x; i < x + w; i++) {
        if (i >= 0 && i < SIZE && j >= 0 && j < SIZE) this.pixels.set(color, (j * SIZE + i) * 3);
      }
    }
  }

  // Draws text with its top-left corner at (x, y), centered on x when x is null.
  text(text, x, y, scale, color) {
    let left = x ?? Math.floor((SIZE - textWidth(text, scale)) / 2);
    for (const ch of text) {
      const columns = glyph(ch);
      for (let c = 0; c < 5; c++) {
        for (let row = 0; row < 8; row++) {
          if (columns[c] & (1 << row)) {
            this.fillRect(left + c * scale, y + row * scale, scale, scale, color);
          }
        }
      }
      left += 6 * scale;
    }
  }
}

// Returns { width, height, rgb } for a channel: its last segment large, and
// the segment before it small above.
export function channelImage(channel) {
  const segments = channel.split('.');
  const name = segments.at(-1);
  const parent = segments.length > 1 ? segments.at(-2) : null;

  const scale = BIG_SCALES.find((s) => textWidth(name, s) <= MAX_TEXT_WIDTH) ?? BIG_SCALES.at(-1);
  const big = fit(name, scale, MAX_TEXT_WIDTH);

  const canvas = new Canvas();
  if (parent !== null) {
    canvas.text(fit(parent, SMALL_SCALE, MAX_TEXT_WIDTH), null, SMALL_TOP, SMALL_SCALE, PARENT_COLOR);
    canvas.text(big, null, NAME_AREA_TOP + Math.floor((NAME_AREA_HEIGHT - 7 * scale) / 2), scale, NAME_COLOR);
  } else {
    const top = Math.floor((NAME_AREA_TOP + NAME_AREA_HEIGHT + SMALL_TOP - 7 * scale) / 2);
    canvas.text(big, null, top, scale, NAME_COLOR);
  }
  return { width: SIZE, height: SIZE, rgb: canvas.pixels };
}

function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'latin1');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
}

// Encodes 8-bit RGB pixels as a PNG, every row with filter 0.
export function encodePng({ width, height, rgb }) {
  const rows = Buffer.alloc(height * (1 + width * 3));
  for (let y = 0; y < height; y++) {
    const at = y * (1 + width * 3);
    rows[at] = 0;
    rgb.copy(rows, at + 1, y * width * 3, (y + 1) * width * 3);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bit depth
  header[9] = 2; // color type: RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(rows)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// Reads a PNG that encodePng wrote, or any 8-bit RGB or RGBA one with filter 0
// on every row. Used to compare pictures pixel by pixel.
export function decodePng(data) {
  let offset = 8;
  let width = 0;
  let height = 0;
  let channels = 3;
  const idat = [];
  while (offset < data.length) {
    const length = data.readUInt32BE(offset);
    const type = data.toString('latin1', offset + 4, offset + 8);
    const body = data.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') {
      width = body.readUInt32BE(0);
      height = body.readUInt32BE(4);
      channels = body[9] === 6 ? 4 : 3;
    } else if (type === 'IDAT') {
      idat.push(body);
    }
    offset += 12 + length;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const rgb = Buffer.alloc(width * height * 3);
  const stride = 1 + width * channels;
  for (let y = 0; y < height; y++) {
    if (raw[y * stride] !== 0) throw new Error('decodePng reads only filter 0');
    for (let x = 0; x < width; x++) {
      const from = y * stride + 1 + x * channels;
      raw.copy(rgb, (y * width + x) * 3, from, from + 3);
    }
  }
  return { width, height, rgb };
}

// Draws the picture for channel under <assetsDir>/.generated/inbox unless the
// file exists, and returns its iconRef. It writes a temporary file and
// renames it, so macropadd never reads half a picture.
export function writeChannelImage(assetsDir, channel) {
  const ref = `${GENERATED_DIR}/${channel}.png`;
  const file = path.join(assetsDir, ...ref.split('/'));
  if (existsSync(file)) return ref;
  mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, encodePng(channelImage(channel)));
    renameSync(temporary, file);
  } catch (e) {
    try {
      unlinkSync(temporary);
    } catch {
      // Never written.
    }
    throw e;
  }
  return ref;
}
